def nav_ul(current: str) -> str:
    out = []
    for href, icon, label in NAV:
        cur = ' aria-current="page"' if href == current else ""
        out.append(
            f'      <li><a href="{href}"{cur}>'
            f'<span class="nav-icon" aria-hidden="true">{icon}</span>{label}</a></li>'
        )
    return "\n".join(out)


